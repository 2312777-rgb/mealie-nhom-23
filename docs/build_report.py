def clean_output() -> None:
    """Keep only the two reports generated by this script in output/."""
    locked = []
    for item in OUT.iterdir():
        try:
            if item.is_dir():
                shutil.rmtree(item)
            else:
                item.unlink()
        except PermissionError:
            locked.append(item.name)
    if locked:
        print('Skipped locked output files; close Word/Preview and run again:', ', '.join(locked))


